export type DishColor = keyof typeof dishColors;

type DishGeometry =
	| { kind: "circle"; cx: number; cy: number; r: number }
	| {
			kind: "ellipse";
			cx: number;
			cy: number;
			rx: number;
			ry: number;
			rotate?: number;
	  }
	| {
			kind: "rect";
			x: number;
			y: number;
			width: number;
			height: number;
			radius?: number;
			rotate?: number;
	  }
	| { kind: "path"; d: string }
	// 線（麺やソースなど）。fill が線の色になる。
	| { kind: "stroke"; d: string; width: number };

// "tint" は、利用者が選ぶ色（器など）に置き換わる。
export type DishShape = DishGeometry & {
	fill: DishColor | "tint";
	opacity?: number;
};

export type DishPart = {
	id: string;
	label: string;
	// 色を選べる部品（器）の候補。先頭が既定。
	tints: readonly string[];
	shapes: readonly DishShape[];
};

