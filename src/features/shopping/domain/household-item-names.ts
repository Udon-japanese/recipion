function buildHouseholdItemNames(): string[] {
	const names = new Map<string, string>();

	function add(name: string) {
		const normalizedName = normalizeIngredientName(name);

		if (!names.has(normalizedName)) {
			names.set(normalizedName, name);
		}
	}

	for (const baseName of baseNames) {
		add(baseName);

		for (const variant of variantsByBaseName[baseName] ?? []) {
			add(`${baseName} ${variant}`);
			add(`${baseName}${variant}`);
		}
	}

	return [...names.values()];
}

export const householdItemNames: readonly string[] = buildHouseholdItemNames();
